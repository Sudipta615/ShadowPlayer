//! Build-time validation and code generation for the UI catalogue.
//!
//! `locales/en.json` is the source of truth: its keys are stable message ids
//! (`S` + 64-bit FNV-1a of the English text) and its values are the English
//! strings.  The build script scans every `tr!("...")`, `tr_args!("...", ...)`
//! and `tr!(Msg::...)` call site and refuses to compile if a call site has no
//! catalogue entry.  It also refuses to compile if a catalogue entry is no
//! longer used, so the catalogue and the source cannot drift in either
//! direction.
//!
//! The generated `Msg` enum is written to `$OUT_DIR/i18n_generated.rs`.  A
//! literal call site is resolved through a generated `msg_for_key` match, so
//! even the convenient `tr!("English")` form is backed by a real, checked
//! variant rather than an unchecked string.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let locales = manifest.join("locales");
    let en_path = locales.join("en.json");
    let de_path = locales.join("de.json");
    let fr_path = locales.join("fr.json");
    let es_path = locales.join("es.json");
    let ja_path = locales.join("ja.json");
    let zh_path = locales.join("zh.json");
    println!("cargo:rerun-if-changed={}", en_path.display());
    println!("cargo:rerun-if-changed={}", de_path.display());
    println!("cargo:rerun-if-changed={}", fr_path.display());
    println!("cargo:rerun-if-changed={}", es_path.display());
    println!("cargo:rerun-if-changed={}", ja_path.display());
    println!("cargo:rerun-if-changed={}", zh_path.display());

    let en: BTreeMap<String, String> = read_catalogue(&en_path);
    for (name, path) in [
        ("de", &de_path),
        ("fr", &fr_path),
        ("es", &es_path),
        ("ja", &ja_path),
        ("zh", &zh_path),
    ] {
        let cat: BTreeMap<String, String> = read_catalogue(path);
        for key in cat.keys() {
            assert!(
                en.contains_key(key),
                "locales/{name}.json contains unknown key {key}; add it to en.json first"
            );
        }
    }

    let mut used = BTreeSet::new();
    let mut source_files = Vec::new();
    collect_rs(&manifest.join("src"), &mut source_files);
    for path in source_files {
        println!("cargo:rerun-if-changed={}", path.display());
        let source = fs::read_to_string(&path).unwrap_or_else(|e| {
            panic!("could not read {}: {e}", path.display());
        });
        scan_source(&path, &source, &en, &mut used);
    }

    for key in en.keys() {
        assert!(
            used.contains(key),
            "locales/en.json key {key} ({:?}) is not referenced by any tr! call site",
            en[key]
        );
    }

    let mut generated = String::new();
    generated.push_str("// @generated by crates/ui/build.rs — do not edit.\n\n");
    generated.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\n");
    generated.push_str("pub enum Msg {\n");
    for key in en.keys() {
        writeln!(generated, "    {key},").unwrap();
    }
    generated.push_str("}\n\n");
    generated.push_str("impl Msg {\n");
    generated.push_str("    pub const ALL: &'static [Msg] = &[\n");
    for key in en.keys() {
        writeln!(generated, "        Msg::{key},").unwrap();
    }
    generated.push_str("    ];\n\n");
    generated.push_str("    pub fn key(self) -> &'static str {\n        match self {\n");
    for key in en.keys() {
        writeln!(generated, "            Msg::{key} => {key:?},").unwrap();
    }
    generated.push_str("        }\n    }\n\n");
    generated.push_str("    pub fn english(self) -> &'static str {\n        match self {\n");
    for (key, text) in &en {
        writeln!(generated, "            Msg::{key} => {text:?},").unwrap();
    }
    generated.push_str("        }\n    }\n}\n\n");
    generated.push_str("pub fn msg_for_key(key: &str) -> Option<Msg> {\n    match key {\n");
    for key in en.keys() {
        writeln!(generated, "        {key:?} => Some(Msg::{key}),").unwrap();
    }
    generated.push_str("        _ => None,\n    }\n}\n");

    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("i18n_generated.rs");
    fs::write(&out, generated).unwrap_or_else(|e| panic!("could not write {}: {e}", out.display()));
}

fn read_catalogue(path: &Path) -> BTreeMap<String, String> {
    let text = fs::read_to_string(path)
        .unwrap_or_else(|e| panic!("could not read {}: {e}", path.display()));
    serde_json::from_str(&text)
        .unwrap_or_else(|e| panic!("{} is not a JSON string map: {e}", path.display()))
}

fn collect_rs(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect_rs(&path, out);
        } else if path.extension().is_some_and(|e| e == "rs") {
            out.push(path);
        }
    }
    out.sort();
}

fn scan_source(
    path: &Path,
    source: &str,
    en: &BTreeMap<String, String>,
    used: &mut BTreeSet<String>,
) {
    let bytes = source.as_bytes();
    let mut i = 0;
    while i < bytes.len() {
        // Find the next `tr!` or `tr_args!` token.
        let plain = source[i..].find("tr!").map(|o| (i + o, "tr!".len()));
        let args = source[i..]
            .find("tr_args!")
            .map(|o| (i + o, "tr_args!".len()));
        let (pos, len) = match (plain, args) {
            (Some(a), Some(b)) => {
                if a.0 <= b.0 {
                    a
                } else {
                    b
                }
            }
            (a, b) => match a.or(b) {
                Some(found) => found,
                None => break,
            },
        };
        // If the found token is the tail of an identifier, skip it.
        if pos > 0 && is_ident_byte(bytes[pos - 1]) {
            i = pos + len;
            continue;
        }
        i = pos + len;
        let macro_name = &source[pos..pos + len];
        if !is_code(source, pos) {
            i = pos + len;
            continue;
        }
        let mut j = i;
        while j < bytes.len() && bytes[j].is_ascii_whitespace() {
            j += 1;
        }
        if j < bytes.len() && bytes[j] == b'(' {
            j += 1;
            while j < bytes.len() && bytes[j].is_ascii_whitespace() {
                j += 1;
            }
        } else {
            // A doc-comment reference such as ``[`tr!`]`` is not a call.
            continue;
        }
        if j >= bytes.len() {
            break;
        }
        if bytes[j] == b'"' {
            let Some((literal, end)) = parse_string(&source[j..]) else {
                panic!(
                    "{}: malformed string literal in {macro_name}",
                    path.display()
                );
            };
            let key = message_key(&literal);
            let Some(english) = en.get(&key) else {
                panic!(
                    "{}: {macro_name} literal {:?} has no catalogue entry (expected key {key}); \
                     add it to locales/en.json",
                    path.display(),
                    literal
                );
            };
            if english != &literal {
                panic!(
                    "{}: catalogue key {key} contains {:?}, but the call site says {:?}",
                    path.display(),
                    english,
                    literal
                );
            }
            used.insert(key);
            i = j + end;
        } else if source[j..].starts_with("Msg::") {
            let after = j + "Msg::".len();
            let end = source[after..]
                .find(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))
                .map(|o| after + o)
                .unwrap_or(bytes.len());
            let key = &source[after..end];
            assert!(
                en.contains_key(key),
                "{}: {macro_name} refers to Msg::{key}, which is not in locales/en.json",
                path.display()
            );
            used.insert(key.to_string());
            i = end;
        } else {
            panic!(
                "{}: {macro_name} takes a string literal or Msg variant; found `{}`",
                path.display(),
                &source[j..source.len().min(j + 40)]
            );
        }
    }
}

fn is_ident_byte(b: u8) -> bool {
    b.is_ascii_alphanumeric() || b == b'_'
}

/// `true` when `pos` is ordinary Rust code, not a comment or string literal.
/// The scanner only needs this to ignore doc examples such as ``tr!("…")``.
fn is_code(source: &str, pos: usize) -> bool {
    #[derive(Clone, Copy, PartialEq)]
    enum State {
        Code,
        LineComment,
        BlockComment(usize),
        Str,
        RawStr(usize),
    }
    let bytes = source.as_bytes();
    let mut state = State::Code;
    let mut i = 0;
    while i < pos && i < bytes.len() {
        match state {
            State::Code => {
                if bytes[i] == b'/' && bytes.get(i + 1) == Some(&b'/') {
                    state = State::LineComment;
                    i += 2;
                } else if bytes[i] == b'/' && bytes.get(i + 1) == Some(&b'*') {
                    state = State::BlockComment(1);
                    i += 2;
                } else if bytes[i] == b'"' {
                    state = State::Str;
                    i += 1;
                } else if bytes[i] == b'r' && bytes.get(i + 1) == Some(&b'"') {
                    state = State::RawStr(0);
                    i += 2;
                } else if bytes[i] == b'r' && bytes.get(i + 1) == Some(&b'#') {
                    let mut hashes = 0;
                    while bytes.get(i + 1 + hashes) == Some(&b'#') {
                        hashes += 1;
                    }
                    if bytes.get(i + 1 + hashes) == Some(&b'"') {
                        state = State::RawStr(hashes);
                        i += 2 + hashes;
                    } else {
                        i += 1;
                    }
                } else {
                    i += 1;
                }
            }
            State::LineComment => {
                if bytes[i] == b'\n' {
                    state = State::Code;
                }
                i += 1;
            }
            State::BlockComment(depth) => {
                if bytes[i] == b'/' && bytes.get(i + 1) == Some(&b'*') {
                    state = State::BlockComment(depth + 1);
                    i += 2;
                } else if bytes[i] == b'*' && bytes.get(i + 1) == Some(&b'/') {
                    state = if depth == 1 {
                        State::Code
                    } else {
                        State::BlockComment(depth - 1)
                    };
                    i += 2;
                } else {
                    i += 1;
                }
            }
            State::Str => {
                if bytes[i] == b'\\' {
                    i += 2;
                } else if bytes[i] == b'"' {
                    state = State::Code;
                    i += 1;
                } else {
                    i += 1;
                }
            }
            State::RawStr(hashes) => {
                if bytes[i] == b'"' {
                    let mut n = 0;
                    while n < hashes && bytes.get(i + 1 + n) == Some(&b'#') {
                        n += 1;
                    }
                    if n == hashes {
                        state = State::Code;
                        i += 1 + hashes;
                    } else {
                        i += 1;
                    }
                } else {
                    i += 1;
                }
            }
        }
    }
    state == State::Code
}

/// Decode a Rust string literal beginning at `input[0] == '"'`.
/// Returns the decoded text and the number of source bytes consumed.
fn parse_string(input: &str) -> Option<(String, usize)> {
    let bytes = input.as_bytes();
    if bytes.first() != Some(&b'"') {
        return None;
    }
    let mut out = String::new();
    let mut i = 1;
    while i < bytes.len() {
        match bytes[i] {
            b'"' => return Some((out, i + 1)),
            b'\\' => {
                i += 1;
                let c = *bytes.get(i)?;
                match c {
                    b'\\' => out.push('\\'),
                    b'"' => out.push('"'),
                    b'\'' => out.push('\''),
                    b'n' => out.push('\n'),
                    b'r' => out.push('\r'),
                    b't' => out.push('\t'),
                    b'0' => out.push('\0'),
                    b'x' => {
                        let hex = input.get(i + 1..i + 3)?;
                        let value = u8::from_str_radix(hex, 16).ok()?;
                        out.push(value as char);
                        i += 2;
                    }
                    b'u' => {
                        if bytes.get(i + 1) != Some(&b'{') {
                            return None;
                        }
                        let close = input[i + 2..].find('}')? + i + 2;
                        let hex = &input[i + 2..close];
                        let value = u32::from_str_radix(hex, 16).ok()?;
                        out.push(char::from_u32(value)?);
                        i = close;
                    }
                    b'\n' => {
                        // Line continuation: skip following whitespace.
                        while i + 1 < bytes.len() && bytes[i + 1].is_ascii_whitespace() {
                            i += 1;
                        }
                    }
                    _ => return None,
                }
                i += 1;
            }
            _ => {
                let ch = input[i..].chars().next()?;
                out.push(ch);
                i += ch.len_utf8();
            }
        }
    }
    None
}

/// Stable message id: `S` + 64-bit FNV-1a of the UTF-8 English text.
fn message_key(text: &str) -> String {
    let mut hash: u64 = 0xcbf29ce484222325;
    for byte in text.as_bytes() {
        hash ^= u64::from(*byte);
        hash = hash.wrapping_mul(0x100000001b3);
    }
    format!("S{hash:016X}")
}
